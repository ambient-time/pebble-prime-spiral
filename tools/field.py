import math
from pathlib import Path
ROOT=Path(__file__).resolve().parent.parent
N=1800;golden=math.pi*(3-math.sqrt(5));prime=[False,False]+[True]*(N-1)
for p in range(2,math.isqrt(N)+1):
 if prime[p]:
  for k in range(p*p,N+1,p):prime[k]=False
lines=['// Copyright 2026 Luke Steuber. MIT License.', '// Generated by tools/field.py from the supplied prime sunflower.', '#pragma once','#include <stdint.h>', 'typedef struct { int16_t x,y; uint16_t angle; uint8_t prime,depths; } PrimeDot;', 'static const PrimeDot PRIME_DOTS[1799]={']
for i in range(2,N+1):
 r=math.sqrt(i/N);a=i*golden
 depths=(1 if r<.58 else 0)|(2 if r<.8 else 0)|(4 if r<1 else 0)
 lines.append('{%d,%d,%d,%d,%d},'%(round(math.sin(a)*r*16384),round(-math.cos(a)*r*16384),round(a/math.tau*65536)%65536,prime[i],depths))
lines.extend(['};','static const uint8_t PRIME_GAUSSIAN[769]={',','.join(str(round(255*math.exp(-(i/256)**2))) for i in range(769)),'};'])
(ROOT/'src/c/field.h').write_text('\n'.join(lines)+'\n')
print('Prime count:',sum(prime),'dot count:',N-1)
