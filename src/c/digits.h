static void draw_digits(GContext *ctx,const char *value,int x,int y,int scale,GColor color){
  int n=strlen(value),w=(6*n-1)*scale;
  x-=w/2;y-=7*scale/2;
  graphics_context_set_fill_color(ctx,color);
  for(int i=0;i<n;i++){
    char c=value[i];int index=c>='0'&&c<='9'?c-'0':c>='A'&&c<='Z'?c-'A'+10:-1;
    for(int row=0;row<7;row++)for(int col=0;col<5;col++){
      bool lit=index>=0?((s_font[index][row]>>(4-col))&1):(c==':'&&col==2&&(row==2||row==5));
      if(lit)graphics_fill_rect(ctx,GRect(x+i*6*scale+col*scale,y+row*scale,scale,scale),0,GCornerNone);
    }
  }
}
